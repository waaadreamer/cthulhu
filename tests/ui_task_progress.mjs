import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE || '/tmp/cthulhu-ui-check/node_modules/playwright/index.mjs'))
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.addInitScript(() => {
  const Original = window.WebSocket
  window.WebSocket = class extends Original { constructor(...args) { super(...args); window.testSocket = this } }
})
try {
  await page.goto(`http://127.0.0.1:${process.argv[2]}`)
  await page.locator('input[type=password]').fill('test-password')
  await page.getByRole('button', { name: '进入神殿' }).click()
  const a = page.locator('[data-task-id=a]'), b = page.locator('[data-task-id=b]')
  await a.waitFor()
  assert.equal(await a.count(), 1)
  assert.equal(await b.count(), 1)
  assert((await a.innerText()).includes('部署界面修复'))
  assert((await b.innerText()).includes('28节点训练性能'))
  assert(!(await a.innerText()).includes('等待新的有效产物'))
  assert(!(await page.locator('body').innerText()).includes('原始prompt'))
  await a.getByText('依据与操作（1）', { exact: true }).click()
  assert((await a.innerText()).includes('补充回归验证'))
  console.log('PERIOD_TWO')
  await page.getByText(/第二期新增回归验证/).waitFor()
  await page.getByText(/迟到判断：保留第一期证据/).waitFor()
  assert.equal(await a.locator('[data-progress-id]').count(), 2)
  assert.equal(await b.locator('[data-progress-id]').count(), 2)
  assert(!(await page.locator('[data-progress-id=digest_21_a]').innerText()).includes('迟到判断'))
  await page.evaluate(() => window.testSocket.close())
  console.log('RECONNECT')
  await page.getByText(/重连期间新增验证/).waitFor()
  assert.equal(await a.locator('[data-progress-id]').count(), 3)
  await page.reload()
  await page.getByText(/重连期间新增验证/).waitFor()
  assert.equal(await a.count(), 1)
  assert.equal(await a.locator('[data-progress-id]').count(), 3)
  await page.screenshot({ path: 'docs/task-progress/chat.png', fullPage: true })
  await page.getByRole('button', { name: '任务与消息' }).click()
  await page.locator('[data-history-task=a]').click()
  assert((await page.locator('[data-history-task=a]').innerText()).includes('部署界面修复'))
  assert(!(await page.locator('[data-history-task=a]').innerText()).includes('完整任务说明'))
  await page.getByText('部署界面修复', { exact: true }).last().waitFor()
  await page.screenshot({ path: 'docs/task-progress/sidebar.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: task isolation, two periods, late update, action trace, duplicate websocket, reconnect, reload and stable sidebar labels')
} finally { await browser.close() }
