// Browser workflow, real authenticated HTTP/WS and built static assets; fixtures are test-only.
import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE || '/tmp/cthulhu-ui-check/node_modules/playwright/index.mjs'))
const browser = await chromium.launch({ headless: true, executablePath: chromium.executablePath(), args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 850 } })
const errors=[]
page.on('pageerror', (e) => errors.push(e.message))
const root=`http://127.0.0.1:${process.argv[2]}`
try {
  await page.goto(root)
  await page.locator('input[type=password]').fill('test-password')
  await page.getByRole('button', {name:'进入神殿'}).click()
  await page.locator('[data-task-id=task_a]').waitFor()
  assert.equal(await page.locator('[data-task-id=task_a]').count(),1)
  assert.deepEqual(await page.locator('[data-task-id]').evaluateAll((els)=>els.map(e=>e.dataset.taskId)),['task_b','task_a'])
  const a=await page.locator('[data-task-id=task_a]').innerText()
  assert(a.indexOf('甲第一条') < a.indexOf('甲第二条'))
  const positions=await page.evaluate(()=>({owner:document.body.innerText.indexOf('独立主人消息'),a:document.body.innerText.indexOf('甲第一条')}))
  assert(positions.owner<positions.a)
  console.log('STREAM_REQUEST')
  await page.getByText('实时新增进展',{exact:true}).waitFor()
  assert.deepEqual(await page.locator('[data-task-id]').evaluateAll((els)=>els.map(e=>e.dataset.taskId)),['task_a','task_b'])
  assert.equal(await page.locator('[data-task-id=task_b]').count(),1)
  console.log('FINISH_REQUEST')
  await page.getByText('实时新增进展，已收证',{exact:true}).waitFor()
  await page.getByRole('button',{name:'总览'}).click()
  await page.getByRole('button',{name:/长提示执行者/}).click()
  await page.getByText('任务与职责',{exact:true}).click()
  const messageButton=page.getByRole('button',{name:'消息',exact:true})
  const box=await messageButton.boundingBox()
  assert(box && box.y+box.height<850)
  const prompt=page.locator('details > div')
  assert(await prompt.evaluate(e=>e.scrollHeight>e.clientHeight && e.clientHeight<=window.innerHeight*.26))
  await messageButton.click()
  await page.setViewportSize({width:390,height:700})
  const mobileBox=await messageButton.boundingBox()
  assert(mobileBox && mobileBox.y+mobileBox.height<700)
  await page.keyboard.press('Escape')
  await page.setViewportSize({width:1280,height:850})
  await page.getByRole('button',{name:'任务与消息'}).click()
  await page.locator('[data-history-task=task_a]').click()
  await page.waitForFunction(()=>document.querySelector('[data-message-stream]')?.innerText.match(/甲消息/g)?.length===100)
  await page.getByRole('button',{name:'加载更早的消息',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('[data-message-stream]')?.innerText.match(/甲消息/g)?.length===130)
  assert.equal(await page.getByText('旧任务唯一消息',{exact:true}).count(),0)
  await page.getByRole('button',{name:'加载更早的任务',exact:true}).click()
  await page.waitForFunction(()=>document.querySelectorAll('[data-history-task]').length===100)
  await page.getByRole('button',{name:'加载更早的任务',exact:true}).click()
  await page.waitForFunction(()=>document.querySelectorAll('[data-history-task]').length===110)
  assert.equal(await page.locator('[data-history-task]').count(),110)
  await page.locator('[data-history-task=history_000]').click()
  await page.getByText('旧任务唯一消息',{exact:true}).waitFor()
  assert.equal(await page.getByText('甲消息 129',{exact:true}).count(),0)
  await page.getByLabel('任务状态').selectOption('done')
  await page.getByLabel('搜索历史任务').fill('历史任务 000')
  await page.waitForFunction(()=>document.querySelectorAll('[data-history-task]').length===1)
  assert.equal(await page.locator('[data-history-task]').getAttribute('data-history-task'),'history_000')
  await page.getByLabel('任务状态').selectOption('open')
  await page.getByText('没有匹配的任务。',{exact:true}).waitFor()
  assert.equal(await page.locator('[data-history-task]').count(),0)
  assert.deepEqual(errors,[])
  if(process.env.UI_SCREENSHOT) await page.screenshot({path:process.env.UI_SCREENSHOT,fullPage:true})
  console.log(JSON.stringify({ui:'passed',task_groups:2,streaming:'passed',prompt:'desktop+mobile bounded',historical_tasks:110,task_messages:130,timestamp_ties:'no omissions',state_search:'passed',page_errors:errors}))
} finally { await browser.close() }
